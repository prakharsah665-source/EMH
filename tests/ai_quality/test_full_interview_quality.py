def create_full_interview_metric(model):
    """
    Create the GEval metric used to judge the complete
    interview.
    """

    return GEval(
        name="Full Interview Quality",

        criteria="""
Evaluate the overall quality of an AI technical interview.

The interviewer should:

1. Ask questions relevant to the candidate's role and experience.
2. Remember information from previous answers.
3. Ask meaningful follow-up questions.
4. Adapt questions based on the candidate's responses.
5. Avoid unnecessary repetition.
6. Ask technically accurate questions.
7. Maintain a professional and respectful tone.
8. Explore technical concepts beyond simple definitions.
9. Test practical debugging and problem-solving ability.
10. Cover an appropriate range of topics for the role.
11. Progress naturally from introductory questions to deeper
    technical questions.
12. Gather enough information to reasonably evaluate the candidate.
13. End the interview naturally after sufficient evaluation.

The final score should represent the quality of the interview
as a whole, not just the quality of individual questions.
""",

        evaluation_steps=[
            (
                "Identify the candidate's role, experience and "
                "technical background."
            ),

            (
                "Determine whether the interview questions are "
                "relevant to that background and the target role."
            ),

            (
                "Check whether the interviewer remembers and "
                "uses information from earlier answers."
            ),

            (
                "Check whether follow-up questions meaningfully "
                "explore previous candidate responses."
            ),

            (
                "Determine whether the interviewer adapts the "
                "interview based on candidate responses."
            ),

            (
                "Check whether questions are unnecessarily repeated."
            ),

            (
                "Evaluate the technical accuracy of the interview."
            ),

            (
                "Evaluate whether the interviewer maintains a "
                "professional and appropriate tone."
            ),

            (
                "Evaluate the depth of technical questioning."
            ),

            (
                "Evaluate whether practical debugging and "
                "problem-solving skills are tested."
            ),

            (
                "Evaluate the breadth of relevant interview topics."
            ),

            (
                "Evaluate whether the interview progresses naturally."
            ),

            (
                "Determine whether the interview gathers enough "
                "information to evaluate the candidate."
            ),

            (
                "Evaluate whether the interview concludes naturally "
                "after sufficient assessment."
            ),
        ],

        evaluation_params=[
            SingleTurnParams.INPUT,
            SingleTurnParams.ACTUAL_OUTPUT,
        ],

        model=model,
        threshold=QUALITY_THRESHOLD,
    )


